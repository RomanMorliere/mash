const LANGUAGE_KEY = "mash_lang";
const FALLBACK_LANG = "fr";
const originalTitle = document.title;
const textNodes = [];

function captureTextNodes() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const parent = node.parentElement;
    if (!parent) continue;
    if (["SCRIPT", "STYLE"].includes(parent.tagName)) continue;
    const value = node.nodeValue || "";
    const normalized = value.replace(/\s+/g, " ").trim();
    if (!normalized) continue;
    textNodes.push({ node, original: value, normalized });
  }
}

function translateNodeText(lang) {
  const map = TRANSLATIONS[lang] || {};
  textNodes.forEach((entry) => {
    const { node, original, normalized } = entry;
    const translated = map[normalized] || normalized;
    const match = original.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const lead = match ? match[1] : "";
    const tail = match ? match[3] : "";
    node.nodeValue = `${lead}${translated}${tail}`;
  });
}

function applyLanguage(lang) {
  const nextLang = lang === "de" ? "de" : "fr";
  document.documentElement.lang = nextLang;
  localStorage.setItem(LANGUAGE_KEY, nextLang);

  const titlePack = TITLE_TRANSLATIONS[originalTitle];
  if (titlePack) document.title = titlePack[nextLang] || originalTitle;

  translateNodeText(nextLang);

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === nextLang);
  });
}

captureTextNodes();

const savedLang = localStorage.getItem(LANGUAGE_KEY);
applyLanguage(savedLang === "de" ? "de" : FALLBACK_LANG);

document.querySelectorAll(".lang-switch button").forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.lang);
  });
});
